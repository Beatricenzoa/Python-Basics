score = int(input("Enter score:"))

# if statement
if score >= 90:
    print("A")
elif 80 <= score <= 89:
    print("A-")
elif 70 <= score <= 79:
    print("B+")
elif 60 <= score <= 69:
    print("B")
elif score >= 50 >= score:
    print("B-")
elif score >= 40 and score <= 40:
    print("C+")
elif score >= 30 and score <= 30:
    print("C")
elif score >= 20 and score <= 20:
    print("D")
else:
    print("E")


